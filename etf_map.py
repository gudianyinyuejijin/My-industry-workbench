def get_etfs(code: str):
    """返回该行业的活跃ETF列表（[(名称, 代码), ...]，优先多ETF映射）"""
    # 优先使用多ETF映射（etf_final.json），回退到内置 ETF_MAP
    try:
        import os, json
        base = os.path.dirname(os.path.abspath(__file__))
        path = os.path.join(base, "data", "etf_final.json")
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                m = json.load(f)
            if code in m and m[code]:
                return [(x["name"], x["code"]) for x in m[code]]
    except Exception:
        pass
    return ETF_MAP.get(code, [])


